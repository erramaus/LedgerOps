import { expect, test, type Page } from '@playwright/test'
import { FakeMonthEnd, FakeReconciliations, mockApp } from './support'
import { getAdditionalDemoCompany } from '../shared/demoCompanyBooks'
import { demoReport } from '../shared/demoMonthEnd'
import { formatCents } from '../shared/reconciliation'

const nav = (page: Page, name: RegExp) => page.locator('nav.main-nav').getByRole('button', { name })
const chooseClient = (page: Page, name: string) => page.locator('label.client-switcher select').selectOption({ label: name })
const row = (page: Page, testId: string) => page.getByTestId(testId)

test.describe('Generated company books: Green Leaf Landscaping', () => {
  test('switches into its own books, records an invoice receipt, and updates its ledger, reports, tasks, and Month End', async ({ page }) => {
    const reconciliations = new FakeReconciliations()
    const monthEnd = new FakeMonthEnd(reconciliations)
    const harness = await mockApp(page, { reconciliations, monthEnd })
    reconciliations.seedDemo()
    await monthEnd.seedDemo()

    await page.goto('./')
    await expect(page.getByRole('heading', { name: /get to work/i })).toBeVisible()
    await chooseClient(page, 'Green Leaf Landscaping')
    await nav(page, /Transactions/).click()
    await expect(page.locator('.page-content').getByRole('heading', { name: 'Transactions', exact: true })).toBeVisible()
    await expect(page.locator('.transaction-row').filter({ hasText: 'Riverbend Nursery' }).first()).toBeVisible()
    await expect(page.locator('body')).not.toContainText('Home Depot')

    await nav(page, /Reports/).click()
    await page.getByTestId('open-profit-loss').click()
    await expect(page.getByTestId('report-checks')).toContainText('Arithmetic verified')
    const netIncome = await page.getByTestId('row-net-income').innerText()
    expect(netIncome).not.toContain('$4,149.18')
    await page.getByRole('button', { name: '← All reports' }).click()
    await page.getByTestId('open-ar-aging').click()
    await expect(page.getByTestId('report-checks')).toContainText('Agrees with Accounts Receivable')

    await nav(page, /Receivables/).click()
    await page.locator('.finance-list-row').filter({ hasText: 'GL-I202608' }).click()
    const payment = page.getByTestId('invoice-payment-actions')
    await payment.getByLabel('Payment date').fill('2026-08-29')
    await payment.getByLabel('Payment amount').fill('100.00')
    await payment.getByLabel('Deposit to bank account').selectOption('green-leaf-landscaping-checking')
    await payment.getByRole('button', { name: 'Record partial payment' }).click()
    expect(await harness.demoPayments.store.list('green-leaf-landscaping')).toHaveLength(1)
    await expect(page.getByTestId('payment-history-row')).toHaveCount(1)
    await expect(row(page, 'invoice-remaining')).toHaveText('$6,300.00')
    expect(await harness.demoPayments.store.list('abc-plumbing')).toEqual([])

    await nav(page, /Transactions/).click()
    await expect(page.locator('.transaction-row').filter({ hasText: 'GL-I202608' }).filter({ hasText: '$100.00' })).toHaveCount(1)
    await nav(page, /Reports/).click()
    await page.getByTestId('open-ar-aging').click()
    await expect(page.getByTestId('row-total')).toContainText('$12,900.00')
    await expect(page.getByTestId('report-checks')).toContainText('Agrees with Accounts Receivable')
    await nav(page, /Month End/).click()
    await expect(page.getByTestId('month-summary')).toBeVisible()
    await expect(page.getByTestId('month-end-storage')).toBeVisible()
    expect(harness.unexpected).toEqual([])
  })

  test('records Green Leaf\'s missing card charge, clears it explicitly, and completes the matching statement', async ({ page }) => {
    const reconciliations = new FakeReconciliations()
    const monthEnd = new FakeMonthEnd(reconciliations)
    const harness = await mockApp(page, { reconciliations, monthEnd })
    reconciliations.seedDemo()
    await monthEnd.seedDemo()
    const company = getAdditionalDemoCompany('green-leaf-landscaping')!
    const range = { start: '2026-08-01', end: '2026-08-31', label: 'August 2026' }
    const before = Number(demoReport('profit-loss', range, company.ledger).rows.find((item) => item.key === 'net-income')?.cells[0])

    await page.goto('./')
    await expect(page.getByRole('heading', { name: /get to work/i })).toBeVisible()
    await chooseClient(page, 'Green Leaf Landscaping')
    await nav(page, /Reconcile/).click()
    await page.getByRole('button', { name: 'Start reconciliation for Green Leaf Business Visa' }).click()
    await page.getByRole('button', { name: 'Load the demo statement transactions' }).click()
    await page.getByRole('button', { name: /Continue to matching/ }).click()
    const missingLine = page.locator('li').filter({ hasText: 'UNRECOGNIZED CARD PURCHASE' })
    await expect(missingLine).toBeVisible()
    await page.getByRole('button', { name: /Clear all suggested matches/ }).click()
    await page.getByTestId('bulk-confirm').getByRole('button', { name: /^Confirm/ }).click()
    await expect(page.getByTestId('remaining-difference')).toHaveText('$124.50')
    await missingLine.getByRole('button', { name: /Start entering UNRECOGNIZED CARD PURCHASE/ }).click()
    const form = page.getByRole('form', { name: 'New transaction' })
    await expect(form.getByLabel('Date')).toHaveValue('2026-08-19')
    await expect(form.getByLabel('Payee')).toHaveValue('UNRECOGNIZED CARD PURCHASE')
    await expect(form.getByLabel('Amount')).toHaveValue('124.50')
    await form.getByRole('combobox', { name: /^Account/ }).selectOption('green-leaf-landscaping-card')
    await form.getByRole('combobox', { name: /^Transaction type/ }).selectOption('charge')
    await form.getByRole('combobox', { name: /^Category/ }).selectOption('supplies')
    await form.getByRole('button', { name: 'Save transaction' }).click()
    await expect(page.getByTestId('entered-transactions')).toContainText('$124.50')
    await expect(page.getByTestId('remaining-difference')).toHaveText('$124.50')
    await page.getByRole('button', { name: /Mark cleared: UNRECOGNIZED CARD PURCHASE/ }).click()
    await expect(page.getByTestId('remaining-difference')).toHaveText('$0.00')
    await page.getByRole('navigation', { name: 'Reconciliation steps' }).getByRole('button', { name: '4. Review & complete' }).click()
    await page.getByRole('button', { name: /Complete reconciliation/ }).click()
    await expect(page.getByTestId('completed-banner')).toBeVisible()

    await nav(page, /Reports/).click()
    await page.getByTestId('open-profit-loss').click()
    await expect(page.getByTestId('row-net-income')).toContainText(formatCents(before - 12_450))
    await page.getByRole('button', { name: '← All reports' }).click()
    await page.getByTestId('open-general-ledger').click()
    await expect(page.locator('.report-paper')).toContainText('UNRECOGNIZED CARD PURCHASE (entered manually)')
    expect(await harness.demoEntries.store.list('green-leaf-landscaping')).toHaveLength(1)
    expect(await harness.demoEntries.store.list('abc-plumbing')).toEqual([])
    expect(harness.quickBooks.writes).toEqual([])
    expect(harness.unexpected).toEqual([])
  })
})

