import { expect, test, type Page } from '@playwright/test'
import { DEMO_CLIENT_ID } from '../shared/demoBooks'
import { FakeQuickBooks, mockApp } from './support'

const nav = (page: Page, name: RegExp) => page.locator('nav.main-nav').getByRole('button', { name })
const openReconcile = async (page: Page) => {
  await page.goto('./')
  await expect(page.getByRole('heading', { name: /get to work/i })).toBeVisible()
  await nav(page, /Reconcile/).click()
  await page.locator('label.client-switcher select').selectOption({ label: 'ABC Plumbing' })
  await expect(page.getByTestId('storage-label')).toBeVisible()
}
const enterCardReconcile = async (page: Page) => {
  await page.getByRole('button', { name: 'Start reconciliation for Chase Business Credit Card' }).click()
  await page.getByRole('button', { name: 'Load the demo statement transactions' }).click()
  await page.getByLabel(/This is the first reconciliation here/).check()
  await page.getByRole('button', { name: /Continue to matching/ }).click()
  await expect(page.getByRole('heading', { name: 'Match transactions to the statement' })).toBeVisible()
}
const reviewStep = (page: Page) => page.getByRole('navigation', { name: 'Reconciliation steps' }).getByRole('button', { name: '4. Review & complete' })

async function fillCharge(form: ReturnType<Page['getByRole']>, payee: string, amount: string) {
  await form.getByLabel('Date').fill('2026-08-10')
  await form.getByLabel('Payee').fill(payee)
  await form.getByLabel('Amount').fill(amount)
  await form.getByRole('combobox', { name: /^Account/ }).selectOption('chase-card')
  await form.getByRole('combobox', { name: /^Transaction type/ }).selectOption('charge')
  await form.getByRole('combobox', { name: /^Category/ }).selectOption('materials')
}

test.describe('Phase 6: missing demo transactions', () => {
  test('records and clears the $224.20 card charge, completes, and updates transactions, reports and dashboard', async ({ page }) => {
    const { demoEntries, quickBooks, unexpected } = await mockApp(page)
    await openReconcile(page)
    await enterCardReconcile(page)

    await page.getByRole('button', { name: /Clear all suggested matches/ }).click()

    await page.getByTestId('bulk-confirm').getByRole('button', { name: /^Confirm/ }).click()
    await expect(page.getByTestId('remaining-difference')).toHaveText('$224.20')
    await expect(page.getByText(/LedgerOps never adds a transaction on its own/)).toBeVisible()

    await page.getByRole('button', { name: /Start entering HOME DEPOT #4411 \$224.20/ }).click()
    const form = page.getByRole('form', { name: 'New transaction' })
    await expect(form.getByLabel('Date')).toHaveValue('2026-08-08')
    await expect(form.getByLabel('Payee')).toHaveValue('HOME DEPOT #4411')
    await expect(form.getByLabel('Amount')).toHaveValue('224.20')
    await expect(form.getByLabel('Transaction type')).toHaveValue('charge')
    await form.getByLabel('Category').selectOption('materials')
    await form.getByRole('button', { name: 'Save transaction' }).click()

    await expect(page.getByTestId('entered-transactions')).toContainText('$224.20')
    await expect(page.getByTestId('recon-row').filter({ hasText: 'HOME DEPOT #4411' })).toBeVisible()
    await expect(page.getByTestId('remaining-difference')).toHaveText('$224.20')
    await page.getByRole('button', { name: /Mark cleared: HOME DEPOT #4411 \$224.20/ }).click()
    await expect(page.getByTestId('remaining-difference')).toHaveText('$0.00')

    await reviewStep(page).click()
    await expect(page.getByText('Everything checks out')).toBeVisible()
    await page.getByRole('button', { name: /Complete reconciliation/ }).click()
    await expect(page.getByTestId('completed-banner')).toBeVisible()
    expect(await demoEntries.store.list(DEMO_CLIENT_ID)).toHaveLength(1)
    expect(quickBooks.writes).toEqual([])

    await nav(page, /Transactions/).click()
    const transaction = page.locator('.transaction-row').filter({ hasText: 'HOME DEPOT #4411' })
    await expect(transaction).toContainText('$224.20')
    await expect(transaction).toContainText('Materials')

    await nav(page, /Reports/).click()
    await page.getByTestId('open-general-ledger').click()
    const ledgerReport = page.locator('.report-paper')
    await expect(ledgerReport).toContainText('HOME DEPOT #4411 (entered manually)')
    await expect(ledgerReport).toContainText('$224.20')
    await page.getByRole('button', { name: '← All reports' }).click()
    await page.getByTestId('open-profit-loss').click()
    await expect(page.getByTestId('row-net-income')).toContainText('$3,924.98')
    await expect(page.getByTestId('report-checks')).toContainText('Arithmetic verified')

    await page.locator('label.client-switcher select').selectOption({ label: 'ABC Plumbing' })
    await nav(page, /Dashboard/).click()
    const profit = page.locator('.metric-card').filter({ has: page.locator('.metric-label', { hasText: /^Profit$/ }) })
    await expect(profit.locator('strong')).toHaveText('$3,924.98')
    expect(unexpected).toEqual([])
  })

  test('validates fields, prevents duplicates, and preserves edit and reversal history', async ({ page }) => {
    const { demoEntries } = await mockApp(page)
    await openReconcile(page)
    await enterCardReconcile(page)
    await page.getByRole('button', { name: 'Add missing transaction' }).click()
    let form = page.getByRole('form', { name: 'New transaction' })
    await form.getByRole('button', { name: 'Save transaction' }).click()
    await expect(form.getByText('Enter a valid date.')).toBeVisible()
    await expect(form.getByText('Enter who was paid or who paid.')).toBeVisible()
    await expect(form.getByText('Enter an amount greater than zero.')).toBeVisible()
    await expect(form.getByText('Choose the transaction type.')).toBeVisible()
    await expect(form.getByText('Choose the category or account.')).toBeVisible()

    await fillCharge(form, 'Phase Six Test Supply', '23.45')
    await form.getByRole('button', { name: 'Save transaction' }).click()
    await expect(page.getByTestId('entered-transaction')).toHaveCount(1)

    await page.getByRole('button', { name: 'Add missing transaction' }).click()
    form = page.getByRole('form', { name: 'New transaction' })
    await fillCharge(form, 'Phase Six Test Supply', '23.45')
    await form.getByRole('button', { name: 'Save transaction' }).click()
    await expect(page.getByTestId('duplicate-warning')).toContainText('already recorded')
    expect(await demoEntries.store.list(DEMO_CLIENT_ID)).toHaveLength(1)
    await page.getByRole('button', { name: 'This is a separate transaction, save it' }).click()
    await expect(page.getByTestId('entered-transaction')).toHaveCount(2)

    const first = page.getByTestId('entered-transaction').filter({ hasText: 'Phase Six Test Supply' }).first()
    await first.getByRole('button', { name: /Edit Phase Six Test Supply \$23.45/ }).click()
    form = page.getByRole('form', { name: 'Edit transaction' })
    await form.getByLabel('Amount').fill('24.45')
    await form.getByLabel('Reason for the change').fill('Corrected the amount')
    await form.getByRole('button', { name: 'Save correction' }).click()
    const edited = page.getByTestId('entered-transaction').filter({ hasText: 'Phase Six Test Supply' }).first()
    await edited.getByText(/History \(2\)/).click()
    await expect(edited).toContainText('edited: Changed from Charge of $23.45')
    await expect(edited).toContainText('Corrected the amount')
    await edited.getByRole('button', { name: /Reverse Phase Six Test Supply \$24.45/ }).click()
    await page.getByLabel('Reason for reversing').fill('Duplicate after correction')
    await page.getByRole('button', { name: 'Confirm reversal' }).click()
    const reversed = page.getByTestId('entered-transaction').filter({ hasText: 'Phase Six Test Supply' }).first()
    await expect(reversed).toContainText('Reversed')
    await reversed.getByText(/History \(3\)/).click()
    await expect(reversed).toContainText('reversed: Reversed Charge of $24.45')
    await expect(reversed).toContainText('Duplicate after correction')
    expect(await demoEntries.store.list(DEMO_CLIENT_ID)).toHaveLength(2)
    expect((await demoEntries.store.list(DEMO_CLIENT_ID)).find((record) => record.status === 'reversed')?.history).toHaveLength(3)
  })

  test('keeps a demo entry out of another client’s records', async ({ page }) => {
    const { demoEntries } = await mockApp(page)
    await openReconcile(page)
    await enterCardReconcile(page)
    await page.getByRole('button', { name: 'Add missing transaction' }).click()
    const form = page.getByRole('form', { name: 'New transaction' })
    await fillCharge(form, 'ABC Only Test Charge', '31.00')
    await form.getByRole('button', { name: 'Save transaction' }).click()
    expect(await demoEntries.store.list(DEMO_CLIENT_ID)).toHaveLength(1)
    expect(await demoEntries.store.list('green-leaf-landscaping')).toEqual([])

    await page.locator('label.client-switcher select').selectOption({ label: 'Green Leaf Landscaping' })
    await nav(page, /Transactions/).click()
    await expect(page.locator('.transaction-row').filter({ hasText: 'Riverbend Nursery' }).first()).toBeVisible()
    await expect(page.locator('.transaction-row').filter({ hasText: 'ABC Only Test Charge' })).toHaveCount(0)
    await expect(page.locator('.transaction-row').filter({ hasText: 'Home Depot' })).toHaveCount(0)
  })

  test('QuickBooks mode explains the manual QuickBooks step and offers no demo-entry action', async ({ page }) => {
    const quickBooks = new FakeQuickBooks()
    const { demoEntries, unexpected } = await mockApp(page, { quickBooks })
    await page.goto('./')
    await expect(page.getByRole('heading', { name: /get to work/i })).toBeVisible()
    await page.locator('.global-source-area').getByRole('button', { name: 'QuickBooks Sandbox' }).click()
    await nav(page, /Reconcile/).click()
    await page.getByRole('button', { name: 'Start reconciliation for Checking' }).click()
    await page.getByLabel('Beginning balance', { exact: true }).fill('0')
    await page.getByLabel('Ending balance', { exact: true }).fill('0')
    await page.getByLabel(/This is the first reconciliation here/).check()
    await page.getByRole('button', { name: /Continue to matching/ }).click()

    await expect(page.getByTestId('quickbooks-missing-note')).toContainText('Create the missing transaction in QuickBooks')
    await expect(page.getByRole('button', { name: 'Add missing transaction' })).toHaveCount(0)
    expect(demoEntries.mutations).toBe(0)
    expect(await demoEntries.store.list(DEMO_CLIENT_ID)).toEqual([])
    expect(quickBooks.writes).toEqual([])
    expect(unexpected).toEqual([])
  })
})
